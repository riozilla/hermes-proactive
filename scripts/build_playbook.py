"""Generate a single-file reading/installation pack from canonical public material."""
from __future__ import annotations

import re
from pathlib import Path
from repo_common import ROOT

ORDER = [
    'README.md', 'SOUL.additions.md', 'skills/proactive-ops/SKILL.md',
    'skills/proactive-ops/references/OPERATING-POLICY.md',
    'skills/proactive-ops/references/STATE-CONTRACT.md',
    'skills/proactive-ops/references/JOBS.md',
    'skills/proactive-ops/references/LOCAL-SETUP.example.md',
    'skills/proactive-ops/references/ACCEPTANCE-TESTS.md',
    'INSTALL-PROMPT.md', 'SOURCE-NOTES.md',
    'config.merge-fragment.yaml', 'jobs.planning-spec.json',
]


def render(root: Path = ROOT) -> str:
    chunks = [
        '# Hermes Proactive — complete public playbook\n\n'
        'Generated from canonical public files. Do not edit this file directly.\n\n'
        'This is an instruction/specification pack, not an installed runtime. '
        'All personal setup belongs in a private installed copy outside this repository.\n'
    ]
    for relative in ORDER:
        text = (root / relative).read_text(encoding='utf-8').strip()
        if relative.endswith(('.yaml', '.json')):
            text = f'```{Path(relative).suffix[1:]}\n{text}\n```'
        elif Path(relative).parent != Path('.'):
            # Keep documentation links valid in the root-level consolidated file.
            def relink(match: re.Match[str]) -> str:
                target = match.group(1)
                if '://' in target or target.startswith(('#', 'mailto:')):
                    return match.group(0)
                destination, sep, anchor = target.partition('#')
                resolved = ((root / relative).parent / destination).resolve()
                try:
                    new = resolved.relative_to(root.resolve()).as_posix()
                except ValueError:
                    raise ValueError('Playbook link escapes the source repository.')
                return '](' + new + (sep + anchor if sep else '') + ')'
            text = re.sub(r'\]\(([^)]+)\)', relink, text)
        chunks.append(f'\n---\n\n<!-- Source: {relative} -->\n\n{text}\n')
    return '\n'.join(chunks)


if __name__ == '__main__':
    (ROOT / 'PLAYBOOK.md').write_text(render(), encoding='utf-8')
    print('Generated PLAYBOOK.md from canonical public sources.')
